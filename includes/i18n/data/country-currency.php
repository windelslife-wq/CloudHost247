 *    Withdrawn currencies are excluded; renames are collapsed onto the current
 *    code, so the newest codes are present (ZWG, XCG, VES, ...).
 *  - A country is NOT assumed to have a currency of its own. Twenty euro-area
 *    countries share EUR, the CFA francs (XOF/XAF) and the East Caribbean
 *    dollar (XCD) each span many countries, and several territories use USD.
 *  - Where a country has more than one tender the order is the one a shop is
 *    most likely to be configured for (USD before the Panamanian balboa, which
 *    exists only as coinage; INR before the pegged Bhutanese ngultrum).
 *  - Antarctica (AQ), South Georgia (GS) and Palestine (PS) have no universal
 *    currency in ISO 4217 and are deliberately absent: an unknown country
 *    falls back to the configured default currency.
 *
 * Deployers can override any entry (or add a country) through the
 * `country_currency_overrides` configuration key; overrides win over this table
 * but are still filtered through the enabled-currency check.
 *
