$draftApp = $applications->upsert([
    'name' => 'Bleeding Edge', 'slug' => 'bleeding-edge', 'category' => 'developer-tools',
    'kind' => Manifest::KIND_APPLICATION, 'summary' => 'A brand new entry.',
