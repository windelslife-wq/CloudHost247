section('The security validator refuses hostile manifests');

function hostileManifest(array $overrides)
{
    $base = Yaml::parse(file_get_contents(dirname(__DIR__) . '/manifests/uptime-kuma.yaml'));
    foreach ($overrides as $path => $value) {
        $keys = explode('.', $path);
        $ref = &$base;
        foreach ($keys as $key) {
            if (!isset($ref[$key]) || !is_array($ref[$key])) {
                $ref[$key] = [];
            }
            $ref = &$ref[$key];
        }
        $ref = $value;
        unset($ref);
    }
    return Manifest::fromArray($base);
}

$validator = new ManifestValidator();

$privileged = $validator->validate(hostileManifest(['services.app.privileged' => true]));
T::ok('privileged containers are refused', !$privileged['valid']);
T::contains('and say why', 'privileged', strtolower(json_encode($privileged['errors'])));

$hostNetwork = $validator->validate(hostileManifest(['services.app.network_mode' => 'host']));
T::ok('host networking is refused', !$hostNetwork['valid']);

$socket = $validator->validate(hostileManifest([
    'services.app.volumes' => [['name' => 'sock', 'mount' => '/var/run/docker.sock', 'host_path' => '/var/run/docker.sock']],
]));
T::ok('a docker.sock bind mount is refused', !$socket['valid']);

$capabilities = $validator->validate(hostileManifest(['services.app.cap_add' => ['SYS_ADMIN']]));
T::ok('dangerous capabilities are refused', !$capabilities['valid']);

$lowPort = $validator->validate(hostileManifest(['services.app.port' => 80, 'ports' => [80]]));
T::ok('a privileged host port is refused', !$lowPort['valid']);

$unpinned = $validator->validate(hostileManifest(['services.app.image' => 'louislam/uptime-kuma:latest']));
T::ok('an unpinned :latest image is refused', !$unpinned['valid']);

$badRegistry = $validator->validate(hostileManifest(['services.app.image' => 'evil.example.com/up:1.0.0']));
T::ok('an image outside the registry allow-list is refused', !$badRegistry['valid']);

