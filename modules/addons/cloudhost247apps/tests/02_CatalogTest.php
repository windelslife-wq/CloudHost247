$uploadedManifest = <<<'YAML'
schema: 1
id: bleeding-edge
name: Bleeding Edge
category: developer-tools
kind: application
summary: A brand new catalog entry used to prove the approval workflow.
description: This manifest is uploaded through the admin console rather than shipped with the platform, which is the path a new catalog entry always takes before it can be offered to customers.
website: https://example.test
license: MIT
version: 0.1.0
deployment:
  engine: docker-compose
  supported_hosting_types: [vps, dedicated, docker]
requirements:
  cpu_min: 1
  memory_min_mb: 512
  storage_min_mb: 1024
services:
  app:
    image: vendor/bleeding-edge:0.1.0
    port: 8080
    primary: true
    volumes:
      - name: data
        mount: /data
        size_mb: 1024
environment:
  required:
    - key: ADMIN_EMAIL
      description: Administrator address.
      validation: email
  generated:
    - key: APP_KEY
      generate: secret
      secret: true
volumes:
  - name: data
    service: app
    mount: /data
    size_mb: 1024
healthcheck:
  type: http
  path: /health
  port: 8080
domain:
  enabled: true
  required: true
ssl:
  enabled: true
backup:
  enabled: true
update:
  strategy: recreate
YAML;

$created = $versions->create([
    'application_id' => (int) $draftApp['id'],
    'version' => '0.1.0',
    'manifest' => $uploadedManifest,
]);
T::ok('a manifest upload creates a version', (int) $created['version']['id'] > 0);
T::ok('and it validates', $created['validation']['valid']);
T::is('the uploaded manifest is snapshotted with the version', 'bleeding-edge',
    Yaml::parse($created['version']['manifest'])['id']);
T::is('a version whose manifest id does not match the application is refused', 'uptime-kuma',
    (function () use ($versions, $draftApp) {
        try {
            $versions->create([
                'application_id' => (int) $draftApp['id'],
                'version' => '9.9.9',
                'manifest' => file_get_contents(dirname(__DIR__) . '/manifests/uptime-kuma.yaml'),
            ]);
        } catch (ValidationException $e) {
            return 'uptime-kuma';
        }
        return 'accepted';
    })());

$report = json_decode((string) $created['version']['validation_report'], true);
T::ok('the manifest gate passed automatically', $report['manifest']['passed']);
T::ok('the security gate passed automatically', $report['security']['passed']);
foreach (['deployment', 'health_check', 'backup', 'update', 'uninstall'] as $gate) {
    T::ok('the ' . $gate . ' gate starts unproven', !$report[$gate]['passed']);
}

$blocked = T::throws('publishing an untested version is refused', StateException::class,
    function () use ($versions, $created) {
        $versions->publish((int) $created['version']['id']);
    });
T::is('and lists exactly which gates are missing',
    ['deployment', 'health_check', 'backup', 'update', 'uninstall'], $blocked->context()['missing']);
T::throws('and the application cannot be published either', StateException::class,
    function () use ($applications, $draftApp) {
        $applications->publish((int) $draftApp['id']);
    });

foreach (['deployment', 'health_check', 'backup', 'update', 'uninstall'] as $gate) {
    $versions->recordGate((int) $created['version']['id'], $gate, true, ['deployment_id' => 900 + crc32($gate) % 100]);
}
$publishedVersion = $versions->publish((int) $created['version']['id']);
T::is('the version publishes once every gate has passed', 'published', $publishedVersion['status']);
T::ok('and is flagged latest', (bool) $publishedVersion['is_latest']);

$applications->transition((int) $draftApp['id'], ApplicationService::STATUS_VALIDATING);
$applications->transition((int) $draftApp['id'], ApplicationService::STATUS_TESTING);
$applications->transition((int) $draftApp['id'], ApplicationService::STATUS_APPROVED);
$publishedApp = $applications->transition((int) $draftApp['id'], ApplicationService::STATUS_PUBLISHED);
T::is('the application walks the full workflow', ApplicationService::STATUS_PUBLISHED, $publishedApp['status']);
T::is('and becomes deployable', 1, (int) $publishedApp['deployable']);
T::throws('skipping a stage is refused', StateException::class, function () use ($applications, $kuma) {
    $applications->transition((int) $kuma['id'], ApplicationService::STATUS_TESTING);
});

